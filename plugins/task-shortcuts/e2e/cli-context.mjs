import { spawn, execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, appendFileSync, existsSync, readFileSync } from 'node:fs';
import { tmpdir, homedir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';
const mode=process.env.SCENARIO||'next';
const root=mkdtempSync(join(tmpdir(),'shortcuts-context-'));
const repo=join(root,'main');mkdirSync(repo);
const git=(cwd,...a)=>execFileSync('git',a,{cwd,encoding:'utf8',stdio:'pipe'}).toString().trim();
git(repo,'init','-b','feature/test');git(repo,'config','user.name','Test');git(repo,'config','user.email','test@example.invalid');writeFileSync(join(repo,'sample.txt'),'base\n');git(repo,'add','--','sample.txt');execFileSync(join(homedir(),'.claude/bin/safe-git-submit'),['--repo',repo,'--commit','test: 初始化'],{stdio:'pipe'});
const wt=join(root,'task worktree');git(repo,'worktree','add','-b','feature/worktree',wt);
const env={...process.env};delete env.CLAUDECODE;
const p=spawn(join(homedir(),'.local/bin/claude'),['-p','--input-format','stream-json','--output-format','stream-json','--verbose','--setting-sources','user','--strict-mcp-config','--mcp-config','{"mcpServers":{}}','--permission-mode','auto','--max-budget-usd','2','--max-turns','12'],{cwd:repo,env,stdio:['pipe','pipe','pipe']});
let buffer='',stage=0,opened=false;
const send=text=>p.stdin.write(JSON.stringify({type:'user',message:{role:'user',content:text}})+'\n');
p.stderr.on('data',b=>appendFileSync(join(root,'stderr.log'),b));
p.stdout.on('data',b=>{buffer+=b;let i;while((i=buffer.indexOf('\n'))>=0){const line=buffer.slice(0,i);buffer=buffer.slice(i+1);appendFileSync(join(root,'transcript.jsonl'),line+'\n');let e;try{e=JSON.parse(line)}catch{continue}
 if(e.type==='assistant') for(const block of e.message?.content||[]) if(block.type==='tool_use' && block.name==='mcp__task-shortcuts__open_changes' && block.input.workspace?.includes('task worktree')) opened=true;
 if(e.type!=='result')continue;
 console.log(mode+' 阶段 '+stage+': '+JSON.stringify({result:e.result,turns:e.num_turns}));
 if(stage===0){stage=1;send('/'+mode);}else if(stage===1 && e.num_turns===0){stage=2;}else p.stdin.end();
}});
const timer=setTimeout(()=>p.kill(),150000);
const command='printf context-ok > '+JSON.stringify(join(wt,'verified.txt'));
const setup=mode==='next'?`只回复“下一步：在 ${wt} 执行 ${command}，核对 verified.txt 为 context-ok”。这就是明确推荐的下一步，但现在不要执行任何工具，也不要准备缓存。`:`当前任务实际工作区是 ${wt}，不是 session 启动主目录。用户下一次 /changes 要在 Zed 查看该 worktree。现在只回复收到，不执行工具，不准备任何缓存。`;
send('这是用户授权的临时仓库交互测试。'+setup);
await new Promise(r=>p.on('close',r));clearTimeout(timer);
if(mode==='next'){assert.ok(existsSync(join(wt,'verified.txt')));assert.equal(readFileSync(join(wt,'verified.txt'),'utf8'),'context-ok');assert.equal(existsSync(join(repo,'verified.txt')),false);}else assert.ok(opened,'没有通过真实 MCP 打开上下文指定 worktree');
console.log('PASS '+mode+'；日志 '+root);
